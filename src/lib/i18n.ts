export function getActiveLanguage(): SupportedLanguage {
  const pref = loadPrefs().language;
  if (pref && pref !== "auto" && pref in TRANSLATIONS) return pref as SupportedLanguage;
  if (typeof navigator !== "undefined") {
    const nav = navigator.language || "";
    if (nav in TRANSLATIONS) return nav as SupportedLanguage;
    const base = nav.split("-")[0];
    if (base && base in TRANSLATIONS) return base as SupportedLanguage;
  }
  return "en";
}

export function t(key: string, lang?: SupportedLanguage): string {
  const target = lang ?? getActiveLanguage();
  const dict = TRANSLATIONS[target] ?? TRANSLATIONS.en;
  return dict[key] ?? TRANSLATIONS.en[key] ?? key;
}

/** "{count}" interpolation, e.g. tf("votes_other", { count: 3 }). */
export function tf(key: string, vars: Record<string, string | number>, lang?: SupportedLanguage): string {
  return t(key, lang).replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? ""));
}

/**
 * Plural pick. French treats 0 and 1 as singular, English (and the fallback)
 * only 1. Missing keys fall back to English silently, never raw keys.
 */
export function tp(oneKey: string, otherKey: string, count: number, lang?: SupportedLanguage): string {
  const l = lang ?? getActiveLanguage();
  const n = Math.abs(Math.floor(count));
  const singular = l === "fr" ? n <= 1 : n === 1;
  return tf(singular ? oneKey : otherKey, { count: n }, l);
}

/** Relative time in the active language (narrow: "2h ago", "il y a 2 h"). */
export function formatRelativeTime(when: string | number | Date, lang?: SupportedLanguage): string {
  const l = lang ?? getActiveLanguage();
  const ms = new Date(when).getTime() - Date.now();
  const abs = Math.abs(ms);
  const minute = 60_000;
  const hour = 3_600_000;
  const day = 86_400_000;
  if (abs < hour) {
    return new Intl.RelativeTimeFormat(l, { numeric: "auto", style: "narrow" }).format(
      Math.trunc(ms / minute),
      "minute",
    );
  }
  if (abs < day) {
    return new Intl.RelativeTimeFormat(l, { numeric: "auto", style: "narrow" }).format(
      Math.trunc(ms / hour),
      "hour",
    );
  }
  if (abs < 30 * day) {
    return new Intl.RelativeTimeFormat(l, { numeric: "auto", style: "narrow" }).format(
      Math.trunc(ms / day),
      "day",
    );
  }
  return new Intl.DateTimeFormat(l, { month: "short", day: "numeric" }).format(new Date(when));
}

/** Grouped numbers ("12,400" / "12 400") in the active language. */
export function formatCountIntl(value: number, lang?: SupportedLanguage): string {
  return new Intl.NumberFormat(lang ?? getActiveLanguage()).format(value);
}

/** Full date for title/aria attributes. */
export function formatFullDate(when: string | number | Date, lang?: SupportedLanguage): string {
  return new Intl.DateTimeFormat(lang ?? getActiveLanguage(), {
    dateStyle: "medium",
    timeStyle: "short",
  }).format(new Date(when));
}

export function useI18n() {
  const [lang, setLang] = useState<SupportedLanguage>(getActiveLanguage);

  useEffect(() => {
    const handle = () => setLang(getActiveLanguage());
    window.addEventListener(PREFS_EVENT, handle);
    return () => window.removeEventListener(PREFS_EVENT, handle);
  }, []);

  return {
    lang,
    t: (key: string) => t(key, lang),
  };
}
