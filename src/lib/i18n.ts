export function getActiveLanguage(): SupportedLanguage {
  const pref = loadPrefs().language as SupportedLanguage;
  if (pref in TRANSLATIONS) return pref;
  return "en";
}

export function t(key: string, lang?: SupportedLanguage): string {
  const target = lang ?? getActiveLanguage();
  const dict = TRANSLATIONS[target] ?? TRANSLATIONS.en;
  return dict[key] ?? TRANSLATIONS.en[key] ?? key;
}

export function useI18n() {
  const [lang, setLang] = useState<SupportedLanguage>(getActiveLanguage);

  useEffect(() => {
    const handle = () => setLang(getActiveLanguage());
    window.addEventListener(PREFS_EVENT, handle);
    return () => window.removeEventListener(PREFS_EVENT, handle);
  }, []);

  return {
    lang,
    t: (key: string) => t(key, lang),
  };
}
