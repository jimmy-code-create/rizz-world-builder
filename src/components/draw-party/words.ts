export function randomWord(exclude?: string): string {
  const clean = DRAW_WORDS.map((w) => w.trim()).filter(Boolean);
  const pool = exclude ? clean.filter((w) => w.toLowerCase() !== exclude.toLowerCase()) : clean;
  return pool[Math.floor(Math.random() * pool.length)] ?? "cat";
}

export function maskWord(word: string): string {
  return word
    .split("")
    .map((ch) => (ch === " " ? " " : "_"))
    .join(" ");
}
